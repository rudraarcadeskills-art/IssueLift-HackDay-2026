import { ContributionContract, SourceEvidence } from './types';
import { ISSUELIFT_REPO_URL, ISSUELIFT_CANONICAL_URL } from './config';
import { formatCandidateTestFileSummary } from './test-evidence';

export function generateProofBundleMarkdown(contract: ContributionContract): string {
  const meta = contract.issue_metadata;
  const gate = contract.readiness_gate;
  const audit = contract.claim_gate_audit;

  const criteriaRows = contract.criteria
    .map((c) => {
      const typeBadge = c.criterion_type === 'EXPLICIT' ? '`[EXPLICIT]`' : '`[AI-PROPOSED]`';
      const quoteStr = c.exact_quote ? `\n> *Quote:* "${c.exact_quote.replace(/"/g, '\\"')}"` : '';
      const clarifBadge = c.needs_maintainer_clarification ? ' ⚠️ *Needs Clarification*' : '';

      const testFilesStr = c.test_evidence.candidate_test_files.length > 0
        ? c.test_evidence.candidate_test_files
            .map((t) => formatCandidateTestFileSummary(t).fullSummary)
            .join('\n    - ')
        : '_No test evidence found in scanned files_';

      return `### ${c.id}: ${c.description} ${typeBadge} (${c.status})${clarifBadge}${quoteStr}
- **Status Rationale:** ${c.status_rationale}
- **Candidate Files:** ${
        c.candidate_implementation_files.length > 0
          ? c.candidate_implementation_files
              .map((f) => `\`${f.path}\` (${f.verified_exists ? 'Verified Exists' : 'Unverified'})`)
              .join(', ')
          : '_None identified in bounded context_'
      }
- **Test Evidence:** ${c.test_evidence.status}
  - _Test candidates:_
    - ${testFilesStr}
  - _Rationale:_ ${c.test_evidence.rationale}
  - _Manual Validation Scenario:_ ${c.test_evidence.proposed_manual_validation || 'Local reproduction before/after patch.'}
  - _Execution Guarantee:_ Test execution has NOT occurred (IssueLift never runs untrusted code).
`;
    })
    .join('\n');

  // Format AI Engine and Analysis Status truthfully
  let engineStatusText = '';
  if (contract.analysis_status === 'gemma_success') {
    engineStatusText = `- **AI Engine:** Google Gemma 4 (${contract.model_id || 'gemma-4-26b-a4b-it'})\n- **Analysis Status:** Gemma 4 Live Inference Succeeded`;
  } else if (contract.analysis_status === 'baseline_fallback') {
    const reason = contract.engine_details?.fallback_reason || 'Gemma inference failure; fallback applied';
    engineStatusText = `- **AI Engine:** Deterministic Baseline Compiler (Fallback)\n- **Analysis Status:** Gemma request failed — Baseline fallback used: ${reason}`;
  } else if (!contract.ai_configured) {
    engineStatusText = `- **AI Engine:** Deterministic Baseline Compiler\n- **Analysis Status:** Baseline compiler active (GEMMA_API_KEY not configured)`;
  } else {
    engineStatusText = `- **AI Engine:** ${contract.engine || 'Baseline Compiler'}\n- **Analysis Status:** ${contract.analysis_status || 'Complete'}`;
  }

  // Format First-Hour Route cleanly without duplicate numbering
  const firstHourRouteText = contract.first_hour_route
    .map((step, idx) => `${idx + 1}. ${step.replace(/^\d+[\.\)]\s*/, '').trim()}`)
    .join('\n');

  // Format Reproduction Environment if present
  const reproSection = contract.reproduction_environment ? `
### B. Issue Reproduction Environment
- **Reproduction Project URL:** ${contract.reproduction_environment.reproduction_repo_url ? `[${contract.reproduction_environment.reproduction_repo_url}](${contract.reproduction_environment.reproduction_repo_url})` : '_None linked in issue_'}
- **Reproduction Commands:** ${contract.reproduction_environment.reproduction_commands.length > 0 ? contract.reproduction_environment.reproduction_commands.map((c: any) => `\`${typeof c === 'string' ? c : c.command}\``).join(' && ') : '_None specified_'}
- **Manual Validation Scenarios (Localhost/cURL):**
${contract.reproduction_environment.manual_validation_scenarios.length > 0 ? contract.reproduction_environment.manual_validation_scenarios.map((s) => `  - \`${s}\``).join('\n') : '  - _None specified_'}
- **Notes:** ${contract.reproduction_environment.notes || 'Reproduction commands are sourced from issue body/comments and apply strictly to the linked reproduction application, not the target repository.'}
- *Notice: Reproduction commands were NOT executed by IssueLift.*
` : '';

  return `# ISSUELIFT CONTRIBUTION PROOF BUNDLE
*Generated by IssueLift v1.3 • Pre-contribution Contract & TraceMap Engine*
*Checked at:* \`${contract.scan_boundaries.checked_at}\`

---

## 1. Issue Metadata & Readiness Gate
- **Target Issue:** [${meta.owner}/${meta.repo} #${meta.number}: ${meta.title}](${meta.url})
- **Status:** \`${meta.state.toUpperCase()}\`
- **Assignees:** ${meta.assignees.length > 0 ? meta.assignees.map((a) => `@${a.login}`).join(', ') : '_Unassigned_'}
- **Labels:** ${meta.labels.length > 0 ? meta.labels.map((l) => `\`${l.name}\``).join(' ') : '_None_'}
- **Default Branch:** \`${meta.default_branch}\`
- **Readiness Gate Verdict:** **\`${gate.verdict}\`**
${gate.reasons.map((r) => `  - ${r}`).join('\n')}

---

## 2. Executive Contract Summary
- **Summary:** ${contract.issue_summary}
- **Expected Outcome:** ${contract.expected_outcome}

---

## 3. Acceptance-to-Test TraceMap (Contribution Contract)
${criteriaRows}

---

## 4. Setup Truth & Commands

### A. Target Repository Setup (${meta.owner}/${meta.repo})
- **Install Command:** ${
    contract.setup_truth.install_command
      ? `\`${contract.setup_truth.install_command.command}\` (${contract.setup_truth.install_command.label})`
      : '_Not documented in scanned files_'
  }
- **Test Command:** ${
    contract.setup_truth.test_command
      ? `\`${contract.setup_truth.test_command.command}\` (${contract.setup_truth.test_command.label})`
      : '_Not documented in scanned files_'
  }
- **Run Command:** ${
    contract.setup_truth.run_command
      ? `\`${contract.setup_truth.run_command.command}\` (${contract.setup_truth.run_command.label})`
      : '_Not documented in scanned files_'
  }
- **Documentation Found:** README: ${contract.setup_truth.has_readme ? 'Yes' : 'No'} | CONTRIBUTING: ${
    contract.setup_truth.has_contributing ? 'Yes' : 'No'
  }
- **Setup Notes:** ${contract.setup_truth.notes}
- *Notice: Target repository commands are derived from repository manifests/documentation and were NOT executed by IssueLift.*
${reproSection}
---

## 5. Copy-Ready Maintainer Handoff
> **Note for Contributors:** Review and edit this comment before copying to GitHub. IssueLift never posts automatically.

\`\`\`markdown
${contract.maintainer_handoff.clarification_question}

${contract.maintainer_handoff.proposed_criteria_addition ? `Proposed Acceptance Criteria:\n${contract.maintainer_handoff.proposed_criteria_addition}\n` : ''}
${contract.maintainer_handoff.suggested_validation_scenario ? `Validation Plan:\n${contract.maintainer_handoff.suggested_validation_scenario}\n` : ''}
*Context compiled with [IssueLift](${ISSUELIFT_REPO_URL}) (ProofBench verified).*
\`\`\`

---

## 6. First-Hour Route
${firstHourRouteText}

---

## 7. Pre-PR Checklist
${contract.pr_checklist.map((item) => `- [ ] ${item}`).join('\n')}

---

## 8. Deterministic Claim Gate Audit
- **Files in Repository Tree:** ${contract.scan_boundaries.total_files_in_tree}
- **Scanned Evidence Sources:** ${contract.scan_boundaries.scanned_files_count}
- **Tree Truncation Status:** ${contract.scan_boundaries.is_tree_truncated ? 'TRUNCATED (bounded context)' : 'Complete'}
- **Rejected Hallucinated Paths:** ${audit.rejected_paths_count}
- **Rejected Fabricated Source IDs:** ${audit.rejected_source_ids_count}
${engineStatusText}
${audit.warnings.length > 0 ? `\n### Audit Warnings:\n${audit.warnings.map((w) => `- ${w}`).join('\n')}` : ''}

---
*Notice: ProofBench fixtures ensure validation invariants. IssueLift never executes untrusted repository code.*
`;
}

export function generateProofBundleJson(contract: ContributionContract): string {
  const sources: SourceEvidence[] = [...(contract.sources || [])];
  const sourceByPath = new Map<string, SourceEvidence>();
  sources.forEach((s) => {
    if (s.path) {
      sourceByPath.set(s.path, s);
    }
  });

  const existingSourceIds = new Set(sources.map((s) => s.source_id));
  let fileIndex = 1;
  sources.forEach((s) => {
    const m = s.source_id.match(/^file-(\d+)$/);
    if (m) {
      const num = parseInt(m[1], 10);
      if (num >= fileIndex) fileIndex = num + 1;
    }
  });

  const owner = contract.issue_metadata?.owner;
  const repo = contract.issue_metadata?.repo;
  const defaultBranch = contract.issue_metadata?.default_branch || 'main';

  const criteria = (contract.criteria || []).map((c) => {
    const candidate_implementation_files = (c.candidate_implementation_files || []).map((file) => {
      let sourceRecord = sources.find((s) => s.source_id === file.source_id && s.path === file.path);
      if (!sourceRecord) {
        sourceRecord = sourceByPath.get(file.path);
      }

      if (!sourceRecord) {
        while (existingSourceIds.has(`file-${fileIndex}`)) {
          fileIndex++;
        }
        const sourceId = `file-${fileIndex++}`;
        existingSourceIds.add(sourceId);

        const canonicalUrl = owner && repo
          ? `https://github.com/${owner}/${repo}/blob/${defaultBranch}/${file.path}`
          : file.path;

        sourceRecord = {
          source_id: sourceId,
          canonical_url: canonicalUrl,
          path: file.path,
          source_type: 'code',
          excerpt: `Candidate implementation file identified in repository tree (${file.path})`,
          verified_exists: Boolean(file.verified_exists),
          verification_status: file.verified_exists ? 'VERIFIED' : 'UNKNOWN',
          rejection_reason: file.verified_exists ? undefined : 'Path not found in scanned repository tree.',
        };

        sources.push(sourceRecord);
        sourceByPath.set(file.path, sourceRecord);
      }

      return {
        ...file,
        source_id: sourceRecord.source_id,
      };
    });

    return {
      ...c,
      candidate_implementation_files,
    };
  });

  const exportPayload = {
    ...contract,
    sources,
    criteria,
    issuelift_project_url: ISSUELIFT_REPO_URL,
    issuelift_canonical_url: ISSUELIFT_CANONICAL_URL,
  };
  return JSON.stringify(exportPayload, null, 2);
}
